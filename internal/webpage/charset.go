package webpage

import (
	"strings"
	"unicode/utf8"
)

type unsupportedEncoding struct{ label string }

func (e *unsupportedEncoding) Error() string { return "unsupported encoding" }

// decodeBody chooses by priority BOM > header charset > meta.
func decodeBody(body []byte, headerLabel string, isHTML, cut bool) (string, error) {
	switch {
	case len(body) >= 3 && body[0] == 0xEF && body[1] == 0xBB && body[2] == 0xBF:
		return decodeUTF8(body[3:], cut), nil
	case len(body) >= 2 && body[0] == 0xFE && body[1] == 0xFF:
		return "", &unsupportedEncoding{"utf-16be"}
	case len(body) >= 2 && body[0] == 0xFF && body[1] == 0xFE:
		return "", &unsupportedEncoding{"utf-16le"}
	}
	label := normalizeLabel(headerLabel)
	if label == "" && isHTML {
		head := body
		if len(head) > 1024 {
			head = head[:1024]
		}
		label = normalizeLabel(metaCharset(string(head)))
	}
	if label == "" {
		if cut {
			body = trimIncompleteRune(body)
		}
		if !utf8.Valid(body) {
			return "", &unsupportedEncoding{}
		}
		return string(body), nil
	}
	switch label {
	case "utf-8", "utf8", "unicode-1-1-utf-8":
		return decodeUTF8(body, cut), nil
	case "windows-1252", "cp1252", "x-cp1252", "iso-8859-1", "iso8859-1", "iso_8859-1",
		"latin1", "l1", "cp819", "ibm819", "csisolatin1", "us-ascii", "ascii":
		return decodeSingleByte(body, &windows1252), nil
	case "windows-1251", "cp1251", "x-cp1251":
		return decodeSingleByte(body, &windows1251), nil
	case "koi8-r", "koi8", "koi", "koi8_r", "cskoi8r":
		return decodeSingleByte(body, &koi8r), nil
	}
	if !asciiCompatible(label) || !printableASCII(body) {
		return "", &unsupportedEncoding{label}
	}
	return string(body), nil
}

func normalizeLabel(s string) string {
	s = strings.TrimSpace(s)
	s = strings.Trim(s, `"'`)
	return strings.ToLower(strings.TrimSpace(s))
}

// asciiCompatible excludes UTF-7, HZ, UTF-16/32 and ISO-2022.
func asciiCompatible(label string) bool {
	switch {
	case label == "utf-7", label == "hz-gb-2312",
		strings.HasPrefix(label, "utf-16"), strings.HasPrefix(label, "utf-32"),
		strings.HasPrefix(label, "iso-2022-"):
		return false
	}
	return true
}

func printableASCII(b []byte) bool {
	for _, c := range b {
		if c != '\t' && c != '\n' && c != '\r' && (c < 0x20 || c > 0x7E) {
			return false
		}
	}
	return true
}

func decodeUTF8(b []byte, cut bool) string {
	if cut {
		b = trimIncompleteRune(b)
	}
	return strings.ToValidUTF8(string(b), string(utf8.RuneError))
}

func trimIncompleteRune(b []byte) []byte {
	for i := 1; i <= utf8.UTFMax-1 && i <= len(b); i++ {
		c := b[len(b)-i]
		if c < 0x80 {
			return b
		}
		if utf8.RuneStart(c) {
			if !utf8.FullRune(b[len(b)-i:]) {
				return b[:len(b)-i]
			}
			return b
		}
	}
	return b
}

func decodeSingleByte(b []byte, table *[128]rune) string {
	var sb strings.Builder
	sb.Grow(len(b))
	for _, c := range b {
		if c < 0x80 {
			sb.WriteByte(c)
		} else {
			sb.WriteRune(table[c-0x80])
		}
	}
	return sb.String()
}

func metaCharset(head string) string {
	z := newTokenizer(head)
	for {
		t, ok := z.next()
		if !ok {
			return ""
		}
		if t.kind != startTagToken || t.name != "meta" {
			continue
		}
		if v, ok := t.attr("charset"); ok && normalizeLabel(v) != "" {
			return v
		}
		if v, ok := t.attr("http-equiv"); ok && strings.EqualFold(strings.TrimSpace(v), "content-type") {
			if content, ok := t.attr("content"); ok {
				if label := charsetFromContent(content); label != "" {
					return label
				}
			}
		}
	}
}

func charsetFromContent(s string) string {
	lower := strings.ToLower(s)
	pos := 0
	for {
		i := strings.Index(lower[pos:], "charset")
		if i < 0 {
			return ""
		}
		j := pos + i + len("charset")
		for j < len(s) && isHTMLSpace(s[j]) {
			j++
		}
		if j >= len(s) || s[j] != '=' {
			pos = j
			continue
		}
		j++
		for j < len(s) && isHTMLSpace(s[j]) {
			j++
		}
		if j >= len(s) {
			return ""
		}
		if q := s[j]; q == '"' || q == '\'' {
			end := strings.IndexByte(s[j+1:], q)
			if end < 0 {
				return ""
			}
			return s[j+1 : j+1+end]
		}
		k := j
		for k < len(s) && !isHTMLSpace(s[k]) && s[k] != ';' {
			k++
		}
		return s[j:k]
	}
}

